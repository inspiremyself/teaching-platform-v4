#!/usr/bin/env python3
"""Convert H2 SCRIPT output (MODE=MySQL) into MySQL 8 executable SQL.

Used by scripts/common/migrate-h2-to-mysql.sh. See docs/运维文档/2026-09-09-路径C-本地MySQL联调与H2迁移.md.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path


def decode_h2_unicode(value: str) -> str:
    if not value.startswith("U&'") or not value.endswith("'"):
        return value
    body = value[3:-1]
    out: list[str] = []
    i = 0
    while i < len(body):
        if body[i] == "\\" and i + 4 < len(body):
            out.append(chr(int(body[i + 1 : i + 5], 16)))
            i += 5
        else:
            out.append(body[i])
            i += 1
    escaped = "".join(out).replace("\\", "\\\\").replace("'", "''")
    return f"'{escaped}'"


def convert_identifiers(line: str) -> str:
    return re.sub(r'"([^"]+)"', r"`\1`", line)


def convert_common(line: str) -> str:
    line = re.sub(r"CHARACTER VARYING\((\d+)\)", r"VARCHAR(\1)", line, flags=re.I)
    line = re.sub(r"\bCHARACTER VARYING\b", "TEXT", line, flags=re.I)
    line = re.sub(r"\bDOUBLE PRECISION\b", "DOUBLE", line, flags=re.I)
    line = re.sub(r"\b(TEXT|BLOB|JSON)\s+DEFAULT\s+'[^']*'", r"\1", line, flags=re.I)
    # H2 IDENTITY → MySQL AUTO_INCREMENT（勿只留下 BIGINT/INTEGER，否则 INSERT 无默认 id）
    line = re.sub(
        r"(BIGINT|INTEGER) GENERATED BY DEFAULT AS IDENTITY\([^)]+\)(?: DEFAULT ON NULL)?",
        r"\1 AUTO_INCREMENT",
        line,
        flags=re.I,
    )
    line = re.sub(r"\s+NOCHECK\s*;", ";", line, flags=re.I)
    line = re.sub(r" NULLS FIRST", "", line, flags=re.I)
    line = re.sub(r"TIMESTAMP '([^']+)'", r"'\1'", line)
    line = re.sub(r"\bTRUE\b", "1", line)
    line = re.sub(r"\bFALSE\b", "0", line)

    def replace_unicode(match: re.Match[str]) -> str:
        return decode_h2_unicode(match.group(0))

    return re.sub(r"U&'(?:\\[0-9a-fA-F]{4}|[^'])*'", replace_unicode, line)


def convert_line(line: str, in_create_table: bool) -> tuple[str | None, bool]:
    stripped = line.strip()
    if not stripped:
        return "", in_create_table
    if stripped.startswith("--"):
        return None, in_create_table
    if stripped.startswith("SET DB_CLOSE_DELAY"):
        return None, in_create_table
    if stripped.startswith("CREATE USER"):
        return None, in_create_table
    if stripped == ";":
        return None, in_create_table

    line = re.sub(r"CREATE CACHED TABLE", "CREATE TABLE", line, flags=re.I)
    line = re.sub(r'"public"\.', "", line)
    stripped = line.strip()

    if stripped.startswith("("):
        return convert_common(line), in_create_table

    if re.match(r"INSERT INTO", stripped, re.I):
        line = re.sub(r'INSERT INTO "([^"]+)"', r"INSERT INTO `\1`", line, flags=re.I)
        return convert_common(line), False

    if re.match(r"CREATE TABLE", stripped, re.I):
        line = convert_identifiers(line)
        return convert_common(line), True

    if in_create_table:
        line = convert_identifiers(line)
        if stripped.endswith(");") or stripped == ");":
            in_create_table = False
        return convert_common(line), in_create_table

    if re.match(r"(ALTER|CREATE INDEX)", stripped, re.I):
        return convert_common(convert_identifiers(line)), False

    return convert_common(line), False


def main() -> int:
    if len(sys.argv) != 3:
        print(f"Usage: {sys.argv[0]} <h2_dump.sql> <mysql_dump.sql>", file=sys.stderr)
        return 2

    src = Path(sys.argv[1])
    dst = Path(sys.argv[2])
    out_lines: list[str] = [
        "SET NAMES utf8mb4;",
        "SET FOREIGN_KEY_CHECKS=0;",
        "SET SQL_MODE='NO_AUTO_VALUE_ON_ZERO';",
    ]

    in_create_table = False
    for raw in src.read_text(encoding="utf-8").splitlines():
        converted, in_create_table = convert_line(raw, in_create_table)
        if converted is None:
            continue
        out_lines.append(converted)

    out_lines.extend(["SET FOREIGN_KEY_CHECKS=1;", ""])
    dst.write_text("\n".join(out_lines), encoding="utf-8")
    print(f"Wrote {dst} ({len(out_lines)} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
